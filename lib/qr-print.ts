import type { InventoryItem, Organization } from "./types";

export type LabelItem = Pick<InventoryItem,
  "public_id" | "item_name" | "management_no" | "specification" | "unit" |
  "quantity" | "acquired_date" | "item_status" | "storage_location" |
  "manager_main" | "manager_sub"
>;

export function escapeLabelText(value: unknown): string {
  return String(value ?? "").replaceAll("&", "&amp;").replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;").replaceAll('"', "&quot;").replaceAll("'", "&#039;");
}

export function labelValue(value: unknown): string {
  if (value == null || String(value).trim() === "") return "-";
  return String(value).trim();
}

export function labelDate(value: unknown): string {
  if (value == null || value === "") return "-";
  if (value instanceof Date) {
    return Number.isNaN(value.getTime()) ? "-" : value.toISOString().slice(0, 10);
  }
  const text = String(value).trim();
  // SQL DATE is already YYYY-MM-DD. Do not apply a timezone offset.
  return /^\d{4}-\d{2}-\d{2}/.test(text) ? text.slice(0, 10) : text || "-";
}

export function labelFields(item: LabelItem): Array<[string, string]> {
  return [
    ["품명", labelValue(item.item_name)],
    ["관리번호", labelValue(item.management_no)],
    ["규격", labelValue(item.specification)],
    ["단위", labelValue(item.unit)],
    ["수량", labelValue(item.quantity)],
    ["취득일자", labelDate(item.acquired_date)],
    ["상태", labelValue(item.item_status)],
    ["위치", labelValue(item.storage_location)],
    ["관리책임자(정)", labelValue(item.manager_main)],
    ["관리책임자(부)", labelValue(item.manager_sub)],
  ];
}

